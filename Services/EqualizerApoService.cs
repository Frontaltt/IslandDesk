using System.IO;
using System.Globalization;
using System.Text;
using IslandDesk.Models;

namespace IslandDesk.Services;

public static class EqualizerApoService
{
    private const string ManagedFileName = "IslandDesk-Equalizer.txt";
    private const string Marker = "# IslandDesk managed include";

    public static (bool Success, string Message) Apply(AppSettings settings)
    {
        string mainConfig = Environment.ExpandEnvironmentVariables(settings.EqualizerApoConfigPath ?? string.Empty);
        if (string.IsNullOrWhiteSpace(mainConfig) || !File.Exists(mainConfig))
            return (false, "Equalizer APO config.txt was not found. Install Equalizer APO and choose its config.txt file.");

        try
        {
            string folder = Path.GetDirectoryName(mainConfig)!;
            string managedPath = Path.Combine(folder, ManagedFileName);
            string text = File.ReadAllText(mainConfig);
            if (!text.Contains(ManagedFileName, StringComparison.OrdinalIgnoreCase))
            {
                string backup = mainConfig + ".islanddesk.bak";
                if (!File.Exists(backup)) File.Copy(mainConfig, backup);
                string updatedConfig = text.TrimEnd('\r', '\n') + Environment.NewLine + Marker + Environment.NewLine +
                    $"Include: {ManagedFileName}" + Environment.NewLine;
                File.WriteAllText(mainConfig, updatedConfig, new UTF8Encoding(false));
            }

            var bands = settings.EqualizerBandsDb ?? new double[10];
            double maxPositive = bands.Length == 0 ? 0 : Math.Max(0, bands.Max());
            var frequencies = new[] { 31, 62, 125, 250, 500, 1000, 2000, 4000, 8000, 16000 };
            var lines = new List<string>
            {
                "# Generated by Island Desk Studio. Edit this from Island Desk Studio.",
                $"Preamp: -{maxPositive.ToString("0.0", CultureInfo.InvariantCulture)} dB"
            };
            for (int i = 0; i < frequencies.Length; i++)
            {
                double gain = i < bands.Length ? Math.Clamp(bands[i], -12, 12) : 0;
                lines.Add($"Filter {i + 1}: ON PK Fc {frequencies[i]} Hz Gain {gain.ToString("0.0", CultureInfo.InvariantCulture)} dB Q 1.0");
            }
            File.WriteAllLines(managedPath, lines);
            return (true, "Equalizer settings applied. If audio does not change, check the active output device in Equalizer APO Configurator.");
        }
        catch (UnauthorizedAccessException)
        {
            return (false, "Access to the Equalizer APO folder was denied. Run Studio as administrator once or adjust the folder permissions.");
        }
        catch (Exception ex) { return (false, "Could not apply the equalizer: " + ex.Message); }
    }
    public static (bool Success, string Message) Disable(string configPath)
    {
        string mainConfig = Environment.ExpandEnvironmentVariables(configPath ?? string.Empty);
        if (!File.Exists(mainConfig)) return (true, "Equalizer APO is not connected. Island Desk will continue without it.");
        try
        {
            string[] lines = File.ReadAllLines(mainConfig);
            var filtered = lines.Where(line =>
                !line.Contains(Marker, StringComparison.OrdinalIgnoreCase) &&
                !line.Contains(ManagedFileName, StringComparison.OrdinalIgnoreCase)).ToArray();
            File.WriteAllText(mainConfig, string.Join(Environment.NewLine, filtered) + Environment.NewLine, new UTF8Encoding(false));
            string managed = Path.Combine(Path.GetDirectoryName(mainConfig)!, ManagedFileName);
            if (File.Exists(managed)) File.Delete(managed);
            return (true, "Island Desk equalizer disabled.");
        }
        catch (UnauthorizedAccessException)
        {
            return (false, "Access to config.txt was denied. Permission to the Equalizer APO folder is required.");
        }
        catch (Exception ex) { return (false, "Could not disable the equalizer: " + ex.Message); }
    }

}
